`timescale 1ns / 1ps
`include "common_definitions.vh"

// Simulates the whole accelerator.
//
// The BRAMs are preloaded with the data set selected by FALCON_BRAM_INIT_DIR (mem/instruction_dispatch_tb/<alg><N>),
// which requires DEBUG_BRAMS. `make test-sv TESTS=instruction_dispatch_tb_<alg><N>` sets this together with N and ALGORITHM.
//
//   ALGORITHM = 0 (sign):   signs the message, checks that the signature is accepted and that the generated signature
//                           (written to generated_signature.hex in the simulation directory) equals
//                           sign<N>/expected_signature.hex. The expected signature was generated by this design and
//                           checked to be a valid Falcon signature with scripts/falcon_verify.py.
//
//                           With VERIFY_GENERATED = 1 it then also resets the accelerator, loads the public key and
//                           message together with the generated signature, and checks that the accelerator accepts it.
//
//   ALGORITHM = 1 (verify): verifies the signature from the data set and checks that it is accepted. Then loads the
//                           same signature with one coefficient changed and checks that it is rejected.
module instruction_dispatch_tb;

  parameter int N = 512;
  parameter int ALGORITHM = 0;  // 0 = sign, 1 = verify
  parameter bit VERIFY_GENERATED = 1;

  localparam int SIGNATURE_BLOCK_COUNT = N == 512 ? 40 : 78;     // 128-bit words of compressed signature
  localparam int GENERATED_SIGNATURE_ADDR = N == 512 ? 256 : 512; // in BRAM0, after signing
  localparam int PUBLIC_KEY_BLOCK_COUNT = N / 2;
  localparam int MESSAGE_BLOCK_COUNT = 8;  // length + 7 blocks of salt and message
  localparam int TIMEOUT_CYCLES = N == 512 ? 400_000 : 800_000;

  logic clk, rst_n;

  logic ext_bram_en;
  logic [19:0] ext_bram_addr;
  logic [15:0] ext_bram_we;
  logic [127:0] ext_bram_din;
  logic [127:0] ext_bram_dout;

  logic start;
  logic done;
  logic signature_accepted;
  logic signature_rejected;

  logic [1:0] algorithm_select;

  instruction_dispatch #(
                         .N(N)
                       ) instruction_dispatch (
                         .clk(clk),
                         .rst_n(rst_n),
                         .start(start),
                         .algorithm_select(algorithm_select),

                         .done(done),
                         .signature_accepted(signature_accepted),
                         .signature_rejected(signature_rejected),

                         .ext_bram_en(ext_bram_en),
                         .ext_bram_addr(ext_bram_addr),
                         .ext_bram_din(ext_bram_din),
                         .ext_bram_dout(ext_bram_dout),
                         .ext_bram_we(ext_bram_we)
                       );

  always #5 clk = ~clk;

  // External BRAM access, as done by the software through the AXI BRAM controller
  task automatic ext_write(input int bank, input int addr, input logic [127:0] data);
    ext_bram_en <= 1;
    ext_bram_addr <= {3'(bank), 13'(addr), 4'b0};
    ext_bram_din <= data;
    ext_bram_we <= 16'hffff;
    @(posedge clk);
    ext_bram_we <= 0;
    ext_bram_en <= 0;
  endtask

  task automatic ext_read(input int bank, input int addr, output logic [127:0] data);
    ext_bram_en <= 1;
    ext_bram_addr <= {3'(bank), 13'(addr), 4'b0};
    ext_bram_we <= 0;
    repeat (3) @(posedge clk);  // BRAM read latency is 2 cycles
    #1;
    data = ext_bram_dout;
    @(posedge clk);
    ext_bram_en <= 0;
  endtask

  logic [127:0] signature [SIGNATURE_BLOCK_COUNT];
  logic [127:0] expected_signature [SIGNATURE_BLOCK_COUNT];
  logic [127:0] public_key [PUBLIC_KEY_BLOCK_COUNT];
  logic [127:0] message [MESSAGE_BLOCK_COUNT];

  // Runs the selected algorithm and checks the result
  task automatic run(input logic [1:0] alg, input string name, input bit expect_accept = 1);
    int cycles = 0;
    algorithm_select <= alg;
    start <= 1;
    @(posedge clk);
    start <= 0;
    while (done !== 1'b1) begin
      @(posedge clk);
      if (++cycles > TIMEOUT_CYCLES)
        $fatal(1, "%s did not finish within %0d cycles", name, TIMEOUT_CYCLES);
    end
    if (signature_accepted === expect_accept && signature_rejected === !expect_accept)
      $display("%s: signature %s as expected (%0d cycles)", name, expect_accept ? "accepted" : "rejected", cycles);
    else if (signature_accepted === 1'b1 && signature_rejected === 1'b0)
      $fatal(1, "%s: signature accepted, expected it to be rejected", name);
    else if (signature_accepted === 1'b0 && signature_rejected === 1'b1)
      $fatal(1, "%s: signature rejected", name);
    else
      $fatal(1, "%s: unknown status (accepted=%b, rejected=%b)", name, signature_accepted, signature_rejected);
  endtask

  // Loads public key, signature and message through the external BRAM port
  task automatic load_verify_inputs();
    reset();
    for (int i = 0; i < PUBLIC_KEY_BLOCK_COUNT; i++)
      ext_write(0, i, public_key[i]);
    for (int i = 0; i < SIGNATURE_BLOCK_COUNT; i++)
      ext_write(1, i, signature[i]);
    for (int i = 0; i < MESSAGE_BLOCK_COUNT; i++)
      ext_write(6, i, message[i]);
  endtask

  task automatic reset();
    rst_n <= 0;
    repeat (2) @(posedge clk);
    rst_n <= 1;
    repeat (2) @(posedge clk);
  endtask

  initial begin
    string sign_dir, verify_dir;

    clk = 1;
    rst_n = 0;
    start = 0;
    algorithm_select = 0;
    ext_bram_en = 0;
    ext_bram_addr = 0;
    ext_bram_we = 0;
    ext_bram_din = 0;
    reset();

    verify_dir = $sformatf("%s/instruction_dispatch_tb/verify%0d", `FALCON_MEM_DIR, N);
    $readmemh({verify_dir, "/bram0.hex"}, public_key);
    $readmemh({verify_dir, "/bram6.hex"}, message);

    if (ALGORITHM == 1) begin
      run(2'b01, $sformatf("verify%0d", N));

      // A corrupted signature (one coefficient changed, still validly encoded) must be rejected
      $readmemh({verify_dir, "/bram1.hex"}, signature);
      for (int i = 0; i < SIGNATURE_BLOCK_COUNT; i++)
        if ($isunknown(signature[i])) signature[i] = 0;  // the file holds fewer words than the padded signature
      signature[3] = signature[3] ^ {56'b0, 8'hff, 64'b0};
      load_verify_inputs();
      run(2'b01, $sformatf("verify%0d of corrupted signature", N), 0);
    end
    else begin
      run(2'b00, $sformatf("sign%0d", N));

      // Read the generated signature
      for (int i = 0; i < SIGNATURE_BLOCK_COUNT; i++)
        ext_read(0, GENERATED_SIGNATURE_ADDR + i, signature[i]);
      $writememh("generated_signature.hex", signature);  // in the simulation directory
      if (signature[0] === 0 || $isunknown(signature[0]))
        $fatal(1, "No signature found at BRAM0[%0d]", GENERATED_SIGNATURE_ADDR);

      sign_dir = $sformatf("%s/instruction_dispatch_tb/sign%0d", `FALCON_MEM_DIR, N);
      $readmemh({sign_dir, "/expected_signature.hex"}, expected_signature);
      for (int i = 0; i < SIGNATURE_BLOCK_COUNT; i++)
        if (signature[i] !== expected_signature[i])
          $fatal(1, "Generated signature differs from expected_signature.hex at word %0d: expected %h, got %h",
                 i, expected_signature[i], signature[i]);
      $display("sign%0d: generated signature matches expected_signature.hex", N);

      if (VERIFY_GENERATED) begin
        // Verify it with the public key and message of the verify data set
        load_verify_inputs();
        run(2'b01, $sformatf("verify%0d of generated signature", N));
      end
    end

    $display("All tests for instruction_dispatch passed!");
    $finish;
  end

endmodule
