# Computes twiddle factors for the FPGA implementation of negative-wrapped NTT and writes rtl/ntt/ntt_twiddle_factor_rom.sv
# This function is taken from the reference C implementation of Falcon, where the table is called GMb/iGMb.
#
# Usage: python3 scripts/NTT_negative_compute_twiddle_factors.py

from pathlib import Path

N = 1024  # N = 1024 also works for all smaller Ns that are powers of 2
Q = 12289  # Modulus
g = 7  # Primitive root
g_inv = pow(g, -1, Q)
R = 2**14 % Q  # Constant for Montgomery reduction

# Computes NTT twiddle factor at index i
def ntt_twiddle_factor(i):
    rev_i = int("{:010b}".format(i)[::-1], 2)  # Bit reverse i
    return R*(pow(g, rev_i, Q)) % Q


# Computes INTT twiddle factor at index i
def intt_twiddle_factor(i):
    rev_i = int("{:010b}".format(i)[::-1], 2)  # Bit reverse i
    return R*(pow(g_inv, rev_i, Q)) % Q


# Computes NTT twiddle factors for NTT of size N
def ntt_twiddle_factors():
    factors = []
    for i in range(N):
        factors.append(ntt_twiddle_factor(i))

    return factors


# Computes INTT twiddle factors for INTT of size N
def intt_twiddle_factors():
    factors = []
    for i in range(N):
        factors.append(intt_twiddle_factor(i))

    return factors


ROM_HEADER = """`timescale 1ns / 1ps
//////////////////////////////////////////////////////////////////////////////////
//
// Read only memory used to store pre-computed twiddle factors for ntt, in Montgomery form (multiplied by 2^14 mod 12289).
//
// Generated by scripts/NTT_negative_compute_twiddle_factors.py
//
//////////////////////////////////////////////////////////////////////////////////


module ntt_twiddle_factor_rom(
    input logic clk,
    input logic mode, // 0: NTT, 1: Inverse NTT
    input logic [9:0] addr,
    output logic signed [14:0] data
  );

  always @(posedge clk) begin
    case({mode, addr})
"""

ROM_FOOTER = """      default: data <= 15'sd0;
    endcase
  end

endmodule
"""


if __name__ == "__main__":
    lines = []
    for mode, factors in ((0, ntt_twiddle_factors()), (1, intt_twiddle_factors())):
        for i, f in enumerate(factors):
            lines.append(f"      11'b{mode}_{i:010b}: data <= 15'sd{f};\n")
    path = Path(__file__).resolve().parent.parent / "rtl" / "ntt" / "ntt_twiddle_factor_rom.sv"
    path.write_text(ROM_HEADER + "".join(lines) + ROM_FOOTER)
    print(f"wrote {path}")
